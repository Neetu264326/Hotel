export const getFoodsByRestaurant = (restaurantId) => {
  return foods.filter((f) => f.restaurantId === Number(restaurantId));
};

export const getFoodsByCategory = (restaurantId, category) => {
  return foods.filter(
    (f) => f.restaurantId === Number(restaurantId) && f.category === category
  );
};

export const getFoodById = (id) => {
  return foods.find((f) => f.id === Number(id));
};

export const searchFoods = (query) => {
  const q = query.toLowerCase();
  return foods.filter(
    (f) =>
      f.name.toLowerCase().includes(q) ||
      f.description.toLowerCase().includes(q) ||
      f.category.toLowerCase().includes(q) ||
      f.tags.some((t) => t.toLowerCase().includes(q))
  );
};

export const getFoodCategories = (restaurantId) => {
  const restaurantFoods = getFoodsByRestaurant(restaurantId);
  const categories = [...new Set(restaurantFoods.map((f) => f.category))];
  return categories;
};

export const getPopularFoods = () => {
  return foods.filter((f) => f.isPopular).slice(0, 8);
};

export const getBestsellerFoods = () => {
  return foods.filter((f) => f.isBestseller).slice(0, 8);
};
